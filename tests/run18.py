import subprocess, time, sys, os, json
from playwright.sync_api import sync_playwright
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
srv = subprocess.Popen([sys.executable, "-m", "http.server", "8778", "--bind", "127.0.0.1", "--directory", here], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
app = subprocess.Popen([sys.executable, "-m", "http.server", "8779", "--bind", "127.0.0.1", "--directory", os.path.join(root, "docs")], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1); errs = []
def watch(pg, tag):
    pg.on("pageerror", lambda e: errs.append(tag + " PAGEERROR " + str(e)))
    pg.on("console", lambda m: m.type == "error" and "ERR_" not in m.text and "fonts" not in m.text and errs.append(tag + " CONSOLE " + m.text))
def day(pg): return pg.locator("[aria-label='The day']").inner_text().split("\n")
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={"width": 430, "height": 1000}); watch(pg, "online")
        pg.goto("http://127.0.0.1:8778/t.html"); pg.wait_for_selector("text=Today’s session", timeout=20000)
        pg.click("[aria-label='Welcome'] button:has-text('Skip for now')")
        pg.wait_for_selector("text=Today’s Office", timeout=15000)
        print("1 today card:", pg.locator("button:has-text('Today’s Office')").inner_text().replace("\n", " "))
        pg.click("button:has-text('Read Matins')"); pg.wait_for_selector("[aria-label='The day'] h2", timeout=20000)
        pg.fill("#office-date", "2026-11-03"); pg.wait_for_timeout(1500)
        print("2 day:", day(pg)[4:6], "| hours:", pg.locator("[aria-label='Hour'] button").all_inner_texts())
        print("  matins (lessons view):", pg.locator("section[id^='office-']").count(), "| chips:", pg.locator("[aria-label='Sections'] button").all_inner_texts())
        for h in ["Lauds", "Prime", "Vespers", "Compline"]:
            pg.locator(f"[aria-label='Hour'] button:has-text('{h}')").click(); pg.wait_for_timeout(1500)
            print(f"  {h}:", pg.locator("section[id^='office-']").count(), "sections |", pg.locator("[aria-label='Sections'] button").all_inner_texts()[:8])
        pg.locator("[aria-label='Hour'] button:has-text('Prime')").click(); pg.wait_for_timeout(1200)
        print("  martyrology:", pg.locator("section[id^='office-']:has-text('Martyrologium')").count())
        # word → vocabulary deck
        pg.locator("section[id^='office-'] .lw").nth(30).click(); pg.wait_for_timeout(1800)
        print("3 word panel:", pg.locator(".fixed").inner_text()[:120].replace("\n", " | "), "| vtap:", json.loads(pg.evaluate("localStorage.getItem('lectio-vulgata-v2')") or "{}").get("vtap", [])[:3])
        pg.locator(".fixed button:has-text('Close')").first.click()
        # Mass
        pg.locator("[aria-label='Liturgy section'] button:has-text('Mass')").click(); pg.wait_for_timeout(2000)
        print("4 mass propers:", pg.locator("[aria-label='Sections'] button").all_inner_texts())
        pg.locator("[aria-label='How much to show'] button:has-text('Whole Mass')").click(); pg.wait_for_timeout(500)
        print("  whole mass sections:", pg.locator("section[id^='office-']").count(), "| rubric sample:", pg.locator("section[id^='office-'] .text-rubric").nth(3).inner_text()[:90])
        pg.fill("#office-date", "2027-03-28"); pg.wait_for_timeout(2000)
        print("  Easter Mass:", day(pg)[4], "|", pg.locator("[aria-label='Sections'] button").all_inner_texts()[:10])
        # Rubrics
        pg.locator("[aria-label='Liturgy section'] button:has-text('Rubrics')").click(); pg.wait_for_selector("text=The 1960 Code of Rubrics", timeout=15000)
        print("5 rubric docs:", pg.locator("[aria-label='Documents'] button span.font-semibold").all_inner_texts())
        pg.fill("#rubrics-q", "91"); pg.wait_for_timeout(300); print("  no. 91:", pg.locator("[aria-label='Search results']").inner_text()[:160].replace("\n", " | "))
        pg.fill("#rubrics-q", "Credo"); pg.wait_for_timeout(300); print("  'Credo':", pg.locator("[aria-label='Search results'] p").first.inner_text())
        pg.fill("#rubrics-q", ""); pg.locator("[aria-label='Documents'] button").nth(2).click(); pg.wait_for_timeout(200)
        print("  missal chapters:", pg.locator("details summary").count(), pg.locator("details summary").all_inner_texts()[:3])
        # read + streak
        pg.locator("[aria-label='Liturgy section'] button:has-text('Office')").click(); pg.wait_for_timeout(800)
        pg.click("button:has-text('Today')") if pg.locator("button:has-text('Today')").count() else None; pg.wait_for_timeout(1200)
        pg.click("button:has-text('Mark as read')"); pg.wait_for_timeout(200)
        print("6 read:", day(pg)[-1])
        pg.fill("#office-date", "2040-01-01"); pg.wait_for_timeout(1200); print("  2040:", day(pg)[-1])
        b.close()
        # offline copy, no network
        b = p.chromium.launch(); oc = b.new_context(viewport={"width": 1000, "height": 900}, offline=True); op = oc.new_page(); watch(op, "offline")
        op.goto("file://" + os.path.join(root, "dist", "lectio-offline.html")); op.wait_for_selector("text=Today’s session", timeout=60000)
        op.click("nav button:has-text('Liturgy')"); op.wait_for_selector("[aria-label='The day'] h2", timeout=60000)
        op.locator("[aria-label='Liturgy section'] button:has-text('Mass')").click(); op.wait_for_timeout(3000)
        print("7 offline copy:", op.locator("[aria-label='The day'] h2").inner_text(), "| mass propers:", op.locator("[aria-label='Sections'] button").count())
        op.locator("[aria-label='Liturgy section'] button:has-text('Rubrics')").click(); op.wait_for_selector("text=The 1960 Code of Rubrics", timeout=20000); print("  rubrics offline: ok")
        b.close()
        # phone app: keep the year offline, then reopen with no network
        b = p.chromium.launch(); ctx = b.new_context(**p.devices["Pixel 7"]); ap = ctx.new_page(); watch(ap, "app")
        ap.goto("http://127.0.0.1:8779/"); ap.wait_for_selector("text=Today’s session", timeout=30000)
        ap.evaluate("navigator.serviceWorker.ready"); ap.wait_for_timeout(2000)
        ap.click("nav button:has-text('Liturgy')"); ap.wait_for_selector("[aria-label='The day'] h2", timeout=30000)
        ap.locator("[aria-label='Liturgy section'] button:has-text('Office')").click()
        ap.click("button:has-text('Keep this year offline')"); ap.wait_for_selector("text=Saved: the Office", timeout=180000)
        ctx.set_offline(True); ap.reload(); ap.wait_for_selector("text=Today’s session", timeout=30000)
        ap.click("nav button:has-text('Liturgy')"); ap.wait_for_selector("[aria-label='The day'] h2", timeout=30000)
        ap.fill("#office-date", "2027-06-29"); ap.wait_for_timeout(2500)
        ap.locator("[aria-label='Liturgy section'] button:has-text('Mass')").click(); ap.wait_for_timeout(2500)
        print("8 app offline:", ap.locator("[aria-label='The day'] h2").inner_text(), "| mass propers:", ap.locator("[aria-label='Sections'] button").count())
        b.close()
finally:
    srv.terminate(); app.terminate()
print("ERRORS:", errs)
