import subprocess, time, json, sys
from playwright.sync_api import sync_playwright
srv = subprocess.Popen([sys.executable, "-m", "http.server", "8765", "--bind", "127.0.0.1"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1); errs = []
def day(pg): return json.loads(pg.evaluate("localStorage.getItem('lectio-vulgata-day')") or "{}")
try:
    with sync_playwright() as p:
        b = p.chromium.launch(); pg = b.new_page(viewport={"width": 430, "height": 950})
        pg.on("pageerror", lambda e: errs.append("PAGEERROR " + str(e)))
        pg.on("console", lambda m: m.type == "error" and "ERR_" not in m.text and errs.append("CONSOLE " + m.text))
        pg.goto("http://127.0.0.1:8765/t.html"); pg.wait_for_selector("text=Today’s session", timeout=20000)
        print("1 welcome:", pg.locator("[aria-label='Welcome']").count(), "| today steps:", pg.locator("[aria-label=\"Today's session\"] li").count())
        pg.click("[aria-label='Welcome'] button:has-text('Skip for now')")
        # vocab via today
        pg.click("text=Learn 10 words"); pg.wait_for_selector("[aria-label='Deck']", timeout=10000)
        print("2 decks:", pg.locator("[aria-label='Deck'] button").count())
        pg.click("[aria-label='Deck'] button:has-text('Summa')"); pg.wait_for_timeout(1500)
        print("  summa card:", pg.locator("article p[lang='la']").first.inner_text(), "|", pg.locator("article p.italic").first.inner_text())
        pg.click("text=Show meaning"); pg.click("button:has-text('Knew it')"); pg.wait_for_timeout(200)
        print("  day after vocab:", day(pg))
        pg.click("[aria-label='Deck'] button:has-text('Principal parts')"); pg.wait_for_timeout(500)
        f = pg.locator("article p[lang='la']").first.inner_text(); pg.click("text=Show principal parts")
        print("  pp:", f, "→", pg.locator("article .reveal p").first.inner_text())
        # passages: accents, structure, quiz, link
        pg.click("nav button:has-text('Passages')"); pg.wait_for_selector("text=Tap any word", timeout=15000)
        before = pg.locator("p.lt").first.inner_text()
        pg.click("[aria-label='Reading aids'] button:has-text('Accents')"); pg.wait_for_timeout(1500)
        after = pg.locator("p.lt").first.inner_text()
        print("3 accents:", before[:60], "→", after[:60])
        pg.click("[aria-label='Reading aids'] button:has-text('Structure')"); pg.wait_for_timeout(1500)
        print("  structure marks:", {c: pg.locator(f"p.lt .{c}").count() for c in ("st-v", "st-nf", "st-sub", "st-nom")})
        lz0 = pg.evaluate("getComputedStyle(document.querySelector('p.lt')).zoom")
        pg.click("[aria-label='Larger text']"); lz1 = pg.evaluate("getComputedStyle(document.querySelector('p.lt')).zoom")
        print("  text size zoom:", lz0, "→", lz1)
        pg.fill("#translation", "So let your light shine before men that they might see I come")
        pg.click("text=Check Translation"); pg.wait_for_timeout(500)
        q = pg.locator("[aria-label=\"Examiner's questions\"] li")
        print("4 quiz questions:", q.count(), "|", [q.nth(i).locator("p").first.inner_text() for i in range(q.count())])
        q.nth(0).locator("button").first.click(); pg.wait_for_timeout(200)
        print("  after answer:", pg.locator("[aria-label=\"Examiner's questions\"] span.num").first.inner_text(), "| explanation:", q.nth(0).locator("p").nth(1).inner_text()[:90])
        pg.click("text=Mark my mistakes"); pg.wait_for_selector("text=Mostly right", timeout=10000)
        pg.click("button:has-text('Got It')"); pg.wait_for_timeout(200)
        print("  day:", day(pg))
        print("  share link button:", pg.locator("text=Copy link to this passage").count())
        # mistakes deck
        pg.click("nav button:has-text('Vocabulary')"); pg.click("[aria-label='Deck'] button:has-text('My mistakes')"); pg.wait_for_timeout(400)
        print("5 mistakes deck card:", pg.locator("article p[lang='la']").first.inner_text(), "|", pg.locator("article .smallcaps").first.inner_text())
        # exam: oral mock + partner + focus
        pg.click("nav button:has-text('Exam sitting')")
        pg.select_option("#exam-scope", "mock"); pg.check("#exam-partner")
        pg.click("text=Start sitting"); pg.wait_for_selector("section[aria-label^='Part'] article", timeout=20000); pg.wait_for_timeout(800)
        print("6 partner keys:", pg.locator("summary:has-text('Examiner’s key')").count())
        pg.click("button:has-text('Focus mode')"); pg.wait_for_timeout(300)
        print("  focus mode: header hidden", pg.locator("header").count() == 0, "| exit button", pg.locator("text=Exit focus").count())
        pg.click("text=Finish and reveal"); pg.wait_for_timeout(500)
        print("  quizzes after reveal:", pg.locator("[aria-label=\"Examiner's questions\"]").count())
        pg.locator("button:has-text('Got It')").first.click(); pg.wait_for_timeout(200)
        print("  day oral:", day(pg).get("oral"))
        pg.click("text=Exit focus"); pg.wait_for_timeout(300)
        print("  today card oral step done:", pg.locator("[aria-label=\"Today's session\"] li:has-text('oral') button.bg-oktint").count())
        # hash link
        pg2 = b.new_page(); pg2.on("pageerror", lambda e: errs.append("PAGEERROR2 " + str(e)))
        pg2.goto("http://127.0.0.1:8765/t.html#p-st2-3-1"); pg2.wait_for_selector("text=Opened from a shared link", timeout=15000)
        print("7 hash link opens:", pg2.locator("article .smallcaps").first.inner_text())
        b.close()
finally: srv.terminate()
print("ERRORS:", errs[:10])
