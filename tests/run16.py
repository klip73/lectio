import subprocess, time, sys, os, json
from playwright.sync_api import sync_playwright
here = os.path.dirname(os.path.abspath(__file__))
srv = subprocess.Popen([sys.executable, "-m", "http.server", "8775", "--bind", "127.0.0.1", "--directory", here], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1); errs = []
try:
    with sync_playwright() as p:
        b = p.chromium.launch(); ctx = b.new_context(viewport={"width": 430, "height": 1000}, accept_downloads=True); pg = ctx.new_page()
        pg.on("pageerror", lambda e: errs.append("PAGEERROR " + str(e)))
        pg.on("console", lambda m: m.type == "error" and "ERR_" not in m.text and errs.append("CONSOLE " + m.text))
        pg.goto("http://127.0.0.1:8775/t.html"); pg.wait_for_selector("text=Today’s session", timeout=20000)
        pg.click("[aria-label='Welcome'] button:has-text('Skip for now')")
        pg.click("nav button:has-text('Guide')"); pg.wait_for_timeout(300)
        print("1 topics:", pg.locator("details summary").count(), "| groups:", pg.locator("section h2").all_inner_texts())
        pg.locator("summary:has-text('Ablative absolute')").click(); pg.wait_for_timeout(200)
        d = pg.locator("details[open]")
        print("  open topic text:", d.inner_text()[:160].replace("\n", " | "))
        d.locator("button:has-text('read it in context')").first.click(); pg.wait_for_selector("text=Tap any word", timeout=15000)
        print("2 opened passage:", pg.locator("article .smallcaps").first.inner_text(), "| verse 23 present:", pg.locator("p.lt sup:has-text('23')").count())
        pg.click("nav button:has-text('Guide')"); pg.locator("summary:has-text('Indirect questions')").click()
        pg.locator("details[open] button:has-text('Drill verses')").click(); pg.wait_for_timeout(500)
        print("3 drill:", pg.locator("text=Drilling").first.inner_text() if pg.locator("text=Drilling").count() else "none")
        pg.click("nav button:has-text('Guide')"); pg.click("[aria-label='Guide section'] button:has-text('The five texts')"); pg.wait_for_timeout(200)
        print("4 parts:", pg.locator("section[aria-label] h2").all_inner_texts(), "| frame rows:", pg.locator("table tbody tr").count())
        pg.locator("button:has-text('Practise Summa Theologiae')").click(); pg.wait_for_selector("text=Tap any word", timeout=15000)
        print("  practise summa →", pg.locator("article .smallcaps").first.inner_text())
        pg.click("nav button:has-text('Guide')"); pg.click("[aria-label='Guide section'] button:has-text('Pronunciation')")
        print("5 pron rows:", pg.locator("[aria-label='Pronunciation'] tbody tr").count(), "|", pg.locator("[aria-label='Pronunciation']").inner_text()[-120:].replace("\n"," "))
        pg.click("[aria-label='Guide section'] button:has-text('Summa vocabulary')"); pg.fill("#terms-filter", "insofar")
        print("6 terms filtered:", pg.locator("[aria-label='Summa vocabulary'] dt").all_inner_texts())
        pg.fill("#terms-filter", "potency"); pg.locator("[aria-label='Summa vocabulary'] dt button").first.click(); pg.wait_for_timeout(1500)
        print("  term → forms:", pg.locator("section[aria-label^='Forms of'] h2").inner_text() if pg.locator("section[aria-label^='Forms of'] h2").count() else "no table")
        # progress file
        pg.click("nav button:has-text('Vocabulary')"); pg.wait_for_timeout(1500)
        if pg.locator("text=Show meaning").count(): pg.click("text=Show meaning"); pg.click("button:has-text('Knew it')")
        pg.get_by_role("button", name="Skill map & backup").click()
        with pg.expect_download() as dl: pg.click("button:has-text('Save progress file')")
        path = dl.value.path(); data = json.load(open(path)); print("7 saved file:", dl.value.suggested_filename, list(data.keys()), data["code"][:12])
        pg.evaluate("localStorage.clear()"); pg.reload(); pg.wait_for_selector("nav[aria-label='Section']", timeout=20000); pg.wait_for_timeout(1500)
        pg.get_by_role("button", name="Skill map & backup").click()
        before = pg.locator("text=words known").locator("..").inner_text()
        pg.set_input_files("input[type=file]", path); pg.wait_for_timeout(500)
        print("  load:", pg.locator("text=Progress loaded").count(), "| words known before/after:", before.split()[0], pg.locator("text=words known").locator("..").inner_text().split()[0])
        b.close()
finally:
    srv.terminate()
print("ERRORS:", errs)
