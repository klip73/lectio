const groupOf = h => (h === "m" ? "m" : h === "x" ? "x" : "d");
function officeStreak(read, today) {
  const set = new Set(read || []);
  let n = dayNum(today), s = 0;
  if (!set.has(n)) n -= 1;
  while (set.has(n)) { s++; n--; }
  return s;
}
/* One day's record (title, rank, commemorations), with the sections of one hour (or "x", the Mass) when asked. */
async function officeDay(iso, hour) {
  const idx = await officeGet("index");
  const yr = +iso.slice(0, 4);
  if (!idx.years.includes(yr)) return { missing: true, years: idx.years };
  const days = await officeGet("days-" + yr);
  const d = days[iso.slice(5)];
  if (!d) return { missing: true, years: idx.years };
  if (!hour) return d;
  const [common, month] = await Promise.all([officeGet("common"), officeGet(groupOf(hour) + "-" + iso.slice(5, 7))]);
  if (idx.fmt === 2) {
    /* the other calendars: sections are line ids; texts in the file's own L, or the shared lines.json */
    const shared = await officeGet("lines");
    const text = id => month.L[id] != null ? month.L[id] : common.L[id] != null ? common.L[id] : shared[id] != null ? shared[id] : "";
    return { ...d, hour, sections: (d.h[hour] || []).map(k => { const sc = common.s[k] || month.s[k]; return sc ? [sc[0].map(text), sc[1].map(text)] : [[], []]; }) };
  }
  return { ...d, hour, sections: (d.h[hour] || []).map(k => common[k] || month[k] || [[], []]) };
}
const normForm = w => w.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/æ/g, "ae").replace(/œ/g, "oe").replace(/j/g, "i").replace(/v/g, "u");
/* Lines carry light markup from the generator: *Heading*, ^red^ (rubrics), {rubric}. A one-letter heading is a drop capital. */
function officeLines(lines) {
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const h = lines[i].match(/^\*([^*\s][^*]*)\*$/);
    if (h && h[1].trim().length === 1 && i + 1 < lines.length) { lines = lines.slice(); lines[i + 1] = h[1].trim() + lines[i + 1]; continue; }
    out.push(h ? { h: h[1].trim() } : { t: lines[i] });
  }
  return out;
}
function OfficeText({ line, latin, onWord, sel }) {
  const parts = line.split(/(\^[^^]*\^|\{[^}]*\})/);
  return parts.map((p, i) => {
    if (!p) return null;
    if (p[0] === "^") return <span key={i} className="text-rubric">{p.slice(1, -1)}</span>;
    if (p[0] === "{") return <span key={i} className="text-[0.85em] italic text-soft">{p.slice(1, -1).replace(/^omittitur$/, "(omitted)")}</span>;
    if (!latin) return p;
    return p.split(/(\p{L}+)/u).map((w, j) => (j % 2 === 0 ? w : (
      <span key={i + ":" + j} role="button" tabIndex={0} className={`lw${sel === w ? " sel" : ""}`} onClick={() => onWord(w)}
        onKeyDown={e => { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); onWord(w); } }}>{w}</span>
    )));
  });
}
function sectionName(la) {
  const h = la.find(l => /^\*[^*\s][^*]{2,}\*$/.test(l.replace(/^\* /, "*")));
  if (h) return h.replace(/^\*\s*|\s*\*$/g, "");
  const ps = la.find(l => /^\^Psalmus \d+/.test(l) || /^\^Canticum/.test(l));
  if (ps) return ps.replace(/^\^|\^.*$/g, "").replace(/\(.*\)/, "").trim();
  const noct = la.find(l => /^\^Nocturnus/.test(l));
  return noct ? noct.replace(/\^/g, "") : "";
}
