/* ---------- Liturgy: the Office (all eight hours) and the Mass of each day, 1960 rubrics, in Latin and English; and the 1960 Code of Rubrics ----------
   Texts and calendar from the Divinum Officium project, generated by tools/office/build_office.py and tools/rubrics/build_rubrics.py. */
const OFFICE_VER = "dev"; /*OFFICE_VER*/
const OFFICE_KEY = "lectio-vulgata-office";
const officeCache = {};
/* In the phone app, fetching a file through the network lets the service worker keep it for offline use. */
function officeFetch(name) { return fetch(`data/office/${name}.json?v=${OFFICE_VER}`).then(r => { if (!r.ok) throw new Error(String(r.status)); }); }
function officeGet(name) {
  if (!officeCache[name]) officeCache[name] = getJSON(`data/office/${name}.json?v=${OFFICE_VER}`).catch(e => { delete officeCache[name]; throw e; });
  return officeCache[name];
}
const isoOf = d => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
const dayNum = iso => Math.round((Date.UTC(+iso.slice(0, 4), +iso.slice(5, 7) - 1, +iso.slice(8, 10)) - Date.UTC(2000, 0, 1)) / DAY);
const RANK_EN = { "I. classis": "First class", "II. classis": "Second class", "III. classis": "Third class", "IV. classis": "Fourth class" };
const HOURS_L = [["m", "Matins", "Matutinum"], ["l", "Lauds", "Laudes"], ["p", "Prime", "Prima"], ["t", "Terce", "Tertia"], ["s", "Sext", "Sexta"], ["n", "None", "Nona"], ["v", "Vespers", "Vesperae"], ["c", "Compline", "Completorium"]];
const groupOf = h => (h === "m" ? "m" : h === "x" ? "x" : "d");
function officeStreak(read, today) {
  const set = new Set(read || []);
  let n = dayNum(today), s = 0;
  if (!set.has(n)) n -= 1;
  while (set.has(n)) { s++; n--; }
  return s;
}
/* One day's record (title, rank, commemorations), with the sections of one hour (or "x", the Mass) when asked. */
async function officeDay(iso, hour) {
  const idx = await officeGet("index");
  const yr = +iso.slice(0, 4);
  if (!idx.years.includes(yr)) return { missing: true, years: idx.years };
  const days = await officeGet("days-" + yr);
  const d = days[iso.slice(5)];
  if (!d) return { missing: true, years: idx.years };
  if (!hour) return d;
  const [common, month] = await Promise.all([officeGet("common"), officeGet(groupOf(hour) + "-" + iso.slice(5, 7))]);
  return { ...d, hour, sections: (d.h[hour] || []).map(k => common[k] || month[k] || [[], []]) };
}
const normForm = w => w.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/æ/g, "ae").replace(/œ/g, "oe").replace(/j/g, "i").replace(/v/g, "u");
/* Lines carry light markup from the generator: *Heading*, ^red^ (rubrics), {rubric}. A one-letter heading is a drop capital. */
function officeLines(lines) {
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const h = lines[i].match(/^\*([^*\s][^*]*)\*$/);
    if (h && h[1].trim().length === 1 && i + 1 < lines.length) { lines = lines.slice(); lines[i + 1] = h[1].trim() + lines[i + 1]; continue; }
    out.push(h ? { h: h[1].trim() } : { t: lines[i] });
  }
  return out;
}
function OfficeText({ line, latin, onWord, sel }) {
  const parts = line.split(/(\^[^^]*\^|\{[^}]*\})/);
  return parts.map((p, i) => {
    if (!p) return null;
    if (p[0] === "^") return <span key={i} className="text-rubric">{p.slice(1, -1)}</span>;
    if (p[0] === "{") return <span key={i} className="text-[0.85em] italic text-soft">{p.slice(1, -1).replace(/^omittitur$/, "(omitted)")}</span>;
    if (!latin) return p;
    return p.split(/(\p{L}+)/u).map((w, j) => (j % 2 === 0 ? w : (
      <span key={i + ":" + j} role="button" tabIndex={0} className={`lw${sel === w ? " sel" : ""}`} onClick={() => onWord(w)}
        onKeyDown={e => { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); onWord(w); } }}>{w}</span>
    )));
  });
}
function sectionName(la) {
  const h = la.find(l => /^\*[^*\s][^*]{2,}\*$/.test(l.replace(/^\* /, "*")));
  if (h) return h.replace(/^\*\s*|\s*\*$/g, "");
  const ps = la.find(l => /^\^Psalmus \d+/.test(l) || /^\^Canticum/.test(l));
  if (ps) return ps.replace(/^\^|\^.*$/g, "").replace(/\(.*\)/, "").trim();
  const noct = la.find(l => /^\^Nocturnus/.test(l));
  return noct ? noct.replace(/\^/g, "") : "";
}
function OfficeSection({ sec, i, showEn, onWord, sel }) {
  const [en, setEn] = useState(false);
  const la = officeLines(sec[0]), eng = officeLines(sec[1]);
  const both = showEn || en;
  const block = (ls, latin) => ls.map((l, k) => l.h
    ? <p key={k} className="smallcaps mt-1 text-[15px] font-semibold text-rubric">{l.h}</p>
    : <p key={k} className={latin ? "latin text-[1.08rem] leading-[1.75] text-ink" : "text-[15px] leading-snug text-soft"}><OfficeText line={l.t} latin={latin} onWord={onWord} sel={sel} /></p>);
  return (
    <section id={"office-" + i} className="scroll-mt-4 rounded-lg border border-rule bg-leaf px-4 py-3 sm:px-5">
      <div className={both ? "grid gap-x-6 gap-y-2 sm:grid-cols-2" : ""}>
        <div lang="la" className="lt">{block(la, true)}</div>
        {both && <div lang="en" className="border-t border-rule pt-2 sm:border-0 sm:pt-0">{block(eng, false)}</div>}
      </div>
      {!showEn && eng.length > 0 && <button type="button" className="mt-1 text-[12px] text-rubric underline underline-offset-2" onClick={() => setEn(x => !x)}>{en ? "Hide English" : "English"}</button>}
    </section>
  );
}
const PROPERS = /^(Introitus|Oratio|Lectio|Epistola|Graduale|Tractus|Allel[uú][ij]a|Sequentia|Evangelium|Offertorium|Secreta|Pr[æa]fatio|Communio|Postcommunio)(\s|$)/;
/* Office or Mass of one day: the text, sections, word help. */
function DayText({ date, hour, onTap, onTable, view }) {
  const [day, setDay] = useState(null);
  const [err, setErr] = useState("");
  const [word, setWord] = useState(null);
  const [lex, setLex] = useState(null);
  const [forms, setForms] = useState(null);
  const [showEn, setShowEn] = useState(!!(readLocal(OFFICE_KEY) || {}).en);
  useEffect(() => { const p = readLocal(OFFICE_KEY) || {}; writeLocal(OFFICE_KEY, { ...p, en: showEn }); }, [showEn]);
  useEffect(() => {
    let alive = true; setDay(null); setErr(""); setWord(null);
    officeDay(date, hour).then(d => alive && setDay(d)).catch(() => alive && setErr("This didn’t load. Check your connection and try again."));
    return () => { alive = false; };
  }, [date, hour]);
  useEffect(() => {
    if (!word || !lex || !forms || !onTap) return;
    const ids = forms[normForm(word)];
    if (ids) onTap([...new Set(ids.slice(0, 1).map(id => lex.lemmas[lex.ana[id][0]][0]))]);
  }, [word, lex, forms]);
  function pickWord(w) {
    setWord(word === w ? null : w);
    if (!lex) loadLex().then(setLex).catch(() => {});
    if (!forms) officeGet("forms").then(setForms).catch(() => {});
  }
  if (err) return <p className="text-[14px] text-warn">{err}</p>;
  if (!day) return <p className="text-[15px] text-soft">Loading…</p>;
  if (day.missing) return null;
  const secs = day.sections.map((s, i) => ({ s, i, name: sectionName(s[0]) }));
  const omitted = x => x.s[0].length <= 1 && /\{omittitur\}/.test(x.s[0][0] || "");
  const shown = view === "lessons" ? secs.filter(x => !omitted(x) && (/^(Hymnus|Lectio|Oratio)/.test(x.name) || x.s[0].some(l => /^\*Lectio \d/.test(l))))
    : view === "propers" ? secs.filter(x => PROPERS.test(x.name)) : secs.filter(x => !omitted(x) || view === "full");
  const chips = shown.map(x => ({ i: x.i, name: x.name || (x.s[0].find(l => /^\*Lectio/.test(l)) || "").replace(/\*/g, "") })).filter(x => x.name && x.name.length < 40);
  const entry = word && forms ? (forms[normForm(word)] || null) : undefined;
  return (
    <>
      <label htmlFor="office-en" className="flex items-center gap-1.5 text-[14px] text-soft"><input id="office-en" type="checkbox" checked={showEn} onChange={e => setShowEn(e.target.checked)} className="h-4 w-4 accent-[#9a2b22]" /> English beside the Latin</label>
      {chips.length > 1 && (
        <nav className="flex flex-wrap gap-1.5" aria-label="Sections">
          {chips.map(c => <button key={c.i} type="button" onClick={() => { const el = document.getElementById("office-" + c.i); if (el) el.scrollIntoView({ behavior: "smooth", block: "start" }); }}
            className="rounded border border-rule bg-paper px-2 py-0.5 text-[12px] text-ink hover:border-soft">{c.name.replace(/^Psalmus /, "Ps ")}</button>)}
        </nav>
      )}
      {shown.length ? shown.map(x => <OfficeSection key={date + hour + x.i} sec={x.s} i={x.i} showEn={showEn} onWord={pickWord} sel={word} />)
        : <p className="text-[14px] text-soft">Nothing to show in this view today.</p>}
      {word && (
        <div className="fixed inset-x-0 bottom-0 z-20 max-h-[45vh] overflow-auto border-t border-rule bg-paper px-4 pb-4 shadow-[0_-4px_16px_rgba(0,0,0,0.08)]">
          <div className="mx-auto max-w-[46rem]">
            {lex && forms ? (entry ? <WordPanel lex={lex} word={word} entry={entry} onClose={() => setWord(null)} where={day.t} onTable={onTable} />
              : <div className="mt-4 flex items-baseline justify-between gap-3 text-[15px]"><span><span lang="la" className="latin font-bold">{word}</span> <span className="text-soft">isn’t in the parsed texts. Try the Forms tab or a dictionary.</span></span><button type="button" onClick={() => setWord(null)} className="text-[13px] text-soft underline">Close</button></div>)
              : <p className="mt-4 text-[14px] text-soft">Looking up…</p>}
          </div>
        </div>
      )}
    </>
  );
}

/* ----- the 1960 Code of Rubrics ----- */
let rubricsPromise = null;
function loadRubrics() { if (!rubricsPromise) rubricsPromise = getJSON("data/rubrics.json").catch(e => { rubricsPromise = null; throw e; }); return rubricsPromise; }
function RubricPara({ p, q }) {
  const sub = p.startsWith("  ");
  const t = p.trim();
  const m = t.match(/^(\d+)\.\s+/);
  const body = m ? t.slice(m[0].length) : t;
  const mark = s => {
    if (!q || q.length < 3 || /^\d+$/.test(q)) return s;
    const i = s.toLowerCase().indexOf(q.toLowerCase());
    return i < 0 ? s : <>{s.slice(0, i)}<mark className="bg-rubrictint text-ink">{s.slice(i, i + q.length)}</mark>{s.slice(i + q.length)}</>;
  };
  return (
    <p className={`whitespace-pre-line text-[15px] leading-relaxed text-ink ${sub ? "pl-5" : ""}`}>
      {m && !sub && <strong className="num mr-1 text-rubric">{m[1]}.</strong>}{mark(m && !sub ? body : t)}
    </p>
  );
}
function RubricsView() {
  const [R, setR] = useState(null);
  const [err, setErr] = useState("");
  const [doc, setDoc] = useState(null);
  const [q, setQ] = useState("");
  useEffect(() => { loadRubrics().then(setR).catch(() => setErr("The rubrics didn’t load. Check your connection and try again.")); }, []);
  if (err) return <p className="text-[14px] text-warn">{err}</p>;
  if (!R) return <p className="text-[15px] text-soft">Loading the rubrics…</p>;
  const query = q.trim().replace(/^no\.?\s*/i, "");
  const hits = [];
  if (query.length >= 3 || /^\d+$/.test(query)) {
    R.docs.forEach(d => d.chapters.forEach((c, ci) => c.paras.forEach((p, pi) => {
      if (hits.length >= 60) return;
      const ok = /^\d+$/.test(query) ? new RegExp("^" + query + "\\.\\s").test(p.trim()) && !p.startsWith("  ") : p.toLowerCase().includes(query.toLowerCase());
      if (ok) hits.push({ d, c, p });
    })));
  }
  const D = doc && R.docs.find(d => d.id === doc);
  return (
    <div className="flex flex-col gap-4">
      <section className="rounded-lg border border-rule bg-leaf px-5 py-4">
        <h2 className="latin text-[1.15rem] font-bold text-ink">The 1960 Code of Rubrics</h2>
        <p className="mt-1 text-[14px] leading-snug text-soft">The rubrics of the 1962 Breviary and Missal, which the Fraternity follows. Search by word, or by number (“91” is the table of precedence).</p>
        <label htmlFor="rubrics-q" className="sr-only">Search the rubrics</label>
        <input id="rubrics-q" value={q} onChange={e => setQ(e.target.value)} placeholder="Search: commemoration, Credo, 91…" className="mt-3 w-full rounded-md border border-rule bg-paper px-3 py-2 text-[15px] text-ink" />
      </section>
      {q.trim() ? (
        <section className="flex flex-col gap-3" aria-label="Search results">
          <p className="text-[13px] text-soft">{hits.length ? `${hits.length}${hits.length >= 60 ? "+" : ""} paragraph${hits.length === 1 ? "" : "s"}` : "No paragraphs match."}</p>
          {hits.map((h, i) => (
            <div key={i} className="rounded-lg border border-rule bg-leaf px-4 py-3">
              <p className="smallcaps mb-1 text-[12px] text-rubric">{h.d.title} · {h.c.title}</p>
              <RubricPara p={h.p} q={query} />
            </div>
          ))}
        </section>
      ) : D ? (
        <section className="flex flex-col gap-3" aria-label={D.title}>
          <button type="button" className="self-start text-[14px] text-rubric underline underline-offset-2" onClick={() => setDoc(null)}>‹ All documents</button>
          <h2 className="latin text-[1.1rem] font-bold text-ink">{D.title}</h2>
          <p className="text-[14px] text-soft">{D.note}</p>
          {D.chapters.map((c, ci) => (
            <details key={ci} className="rounded-lg border border-rule bg-leaf px-4 py-2.5" open={D.chapters.length === 1}>
              <summary className="cursor-pointer text-[15px] font-semibold text-ink">{c.title || D.title}</summary>
              <div lang={D.lang === "la" ? "la" : "en"} className={`mt-2 flex flex-col gap-2 ${D.lang === "la" ? "latin" : ""}`}>{c.paras.map((p, pi) => <RubricPara key={pi} p={p} />)}</div>
            </details>
          ))}
        </section>
      ) : (
        <section className="grid gap-2 sm:grid-cols-2" aria-label="Documents">
          {R.docs.map(d => (
            <button key={d.id} type="button" onClick={() => setDoc(d.id)} className="rounded-lg border border-rule bg-leaf px-4 py-3 text-left hover:border-soft">
              <span className="block text-[15px] font-semibold text-ink">{d.title}</span>
              <span className="block text-[13px] leading-snug text-soft">{d.note}</span>
            </button>
          ))}
        </section>
      )}
      <p className="text-[12px] text-soft">Text as published by Divinum Officium. For questions of practice, follow your ordo and your superiors.</p>
    </div>
  );
}

