/* ---------- The Office: each day's Matins (1960 rubrics) in Latin and English, for daily reading for life ----------
   Text and calendar from the Divinum Officium project, generated by tools/office/build_office.py. */
const OFFICE_VER = "dev"; /*OFFICE_VER*/
const OFFICE_KEY = "lectio-vulgata-office";
const officeCache = {};
/* In the phone app, fetching a file through the network lets the service worker keep it for offline use. */
function officeFetch(name) { return fetch(`data/office/${name}.json?v=${OFFICE_VER}`).then(r => { if (!r.ok) throw new Error(String(r.status)); }); }
function officeGet(name) {
  if (!officeCache[name]) officeCache[name] = getJSON(`data/office/${name}.json?v=${OFFICE_VER}`).catch(e => { delete officeCache[name]; throw e; });
  return officeCache[name];
}
const isoOf = d => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
const dayNum = iso => Math.round((Date.UTC(+iso.slice(0, 4), +iso.slice(5, 7) - 1, +iso.slice(8, 10)) - Date.UTC(2000, 0, 1)) / DAY);
const isoFromNum = n => { const d = new Date(Date.UTC(2000, 0, 1) + n * DAY); return `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, "0")}-${String(d.getUTCDate()).padStart(2, "0")}`; };
const RANK_EN = { "I. classis": "First class", "II. classis": "Second class", "III. classis": "Third class", "IV. classis": "Fourth class" };
function officeStreak(read, today) {
  const set = new Set(read || []);
  let n = dayNum(today), s = 0;
  if (!set.has(n)) n -= 1;
  while (set.has(n)) { s++; n--; }
  return s;
}
async function officeDay(iso) {
  const idx = await officeGet("index");
  const yr = +iso.slice(0, 4);
  if (!idx.years.includes(yr)) return { missing: true, years: idx.years };
  const days = await officeGet("days-" + yr);
  const d = days[iso.slice(5)];
  if (!d) return { missing: true, years: idx.years };
  const [common, month] = await Promise.all([officeGet("common"), officeGet(iso.slice(5, 7))]);
  return { ...d, sections: d.m.map(k => common[k] || month[k] || [[], []]) };
}
const normForm = w => w.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/æ/g, "ae").replace(/œ/g, "oe").replace(/j/g, "i").replace(/v/g, "u");
/* Lines carry light markup from the generator: *Heading*, ^red^, {rubric}. A one-letter heading is a drop capital. */
function officeLines(lines) {
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    let l = lines[i];
    const h = l.match(/^\*([^*\s][^*]*)\*$/);
    if (h && h[1].length === 1 && i + 1 < lines.length) { lines = lines.slice(); lines[i + 1] = h[1] + lines[i + 1]; continue; }
    out.push(h ? { h: h[1] } : { t: l });
  }
  return out;
}
function OfficeText({ line, latin, onWord, sel }) {
  const parts = line.split(/(\^[^^]*\^|\{[^}]*\})/);
  return parts.map((p, i) => {
    if (!p) return null;
    if (p[0] === "^") return <span key={i} className="text-rubric">{p.slice(1, -1)}</span>;
    if (p[0] === "{") return <span key={i} className="text-[0.85em] italic text-soft">{p.slice(1, -1).replace(/^omittitur$/, "(omitted)")}</span>;
    if (!latin) return p;
    return p.split(/(\p{L}+)/u).map((w, j) => (j % 2 === 0 ? w : (
      <span key={i + ":" + j} role="button" tabIndex={0} className={`lw${sel === w ? " sel" : ""}`} onClick={() => onWord(w)}
        onKeyDown={e => { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); onWord(w); } }}>{w}</span>
    )));
  });
}
function sectionName(la) {
  const h = la.find(l => /^\*[^*\s][^*]{2,}\*$/.test(l));
  if (h) return h.slice(1, -1);
  const ps = la.find(l => /^\^Psalmus \d+/.test(l) || /^\^Canticum/.test(l));
  if (ps) return ps.replace(/^\^|\^.*$/g, "").replace(/\(.*\)/, "").trim();
  const noct = la.find(l => /^\^Nocturnus/.test(l));
  return noct ? noct.replace(/\^/g, "") : "";
}
function OfficeSection({ sec, i, showEn, onWord, sel }) {
  const [en, setEn] = useState(false);
  const la = officeLines(sec[0]), eng = officeLines(sec[1]);
  const both = showEn || en;
  const block = (ls, latin) => ls.map((l, k) => l.h
    ? <p key={k} className="smallcaps mt-1 text-[15px] font-semibold text-rubric">{l.h}</p>
    : <p key={k} className={latin ? "latin text-[1.08rem] leading-[1.75] text-ink" : "text-[15px] leading-snug text-soft"}><OfficeText line={l.t} latin={latin} onWord={onWord} sel={sel} /></p>);
  return (
    <section id={"office-" + i} className="scroll-mt-4 rounded-lg border border-rule bg-leaf px-4 py-3 sm:px-5">
      <div className={both ? "grid gap-x-6 gap-y-2 sm:grid-cols-2" : ""}>
        <div lang="la" className="lt">{block(la, true)}</div>
        {both && <div lang="en" className="border-t border-rule pt-2 sm:border-0 sm:pt-0">{block(eng, false)}</div>}
      </div>
      {!showEn && eng.length > 0 && <button type="button" className="mt-1 text-[12px] text-rubric underline underline-offset-2" onClick={() => setEn(x => !x)}>{en ? "Hide English" : "English"}</button>}
    </section>
  );
}
function OfficeMode({ prog, onRead, onTable }) {
  const pref0 = readLocal(OFFICE_KEY) || {};
  const [date, setDate] = useState(() => isoOf(new Date()));
  const [view, setView] = useState(pref0.view === "full" ? "full" : "lessons");
  const [showEn, setShowEn] = useState(!!pref0.en);
  const [day, setDay] = useState(null);
  const [err, setErr] = useState("");
  const [word, setWord] = useState(null);
  const [lex, setLex] = useState(null);
  const [forms, setForms] = useState(null);
  const [saving, setSaving] = useState("");
  useEffect(() => { writeLocal(OFFICE_KEY, { view, en: showEn }); }, [view, showEn]);
  // The app quietly keeps today's Office and the weeks ahead, so it opens with no signal.
  useEffect(() => {
    if (!APP) return;
    const t = new Date(), m1 = String(t.getMonth() + 1).padStart(2, "0"), m2 = String(((t.getMonth() + 1) % 12) + 1).padStart(2, "0");
    const t2 = new Date(t.getFullYear(), t.getMonth() + 1, 1);
    [...new Set(["index", "common", "forms", "days-" + t.getFullYear(), "days-" + t2.getFullYear(), m1, m2])].reduce((p, n) => p.then(() => officeFetch(n).catch(() => {})), Promise.resolve());
  }, []);
  useEffect(() => {
    let alive = true; setDay(null); setErr(""); setWord(null);
    officeDay(date).then(d => alive && setDay(d)).catch(() => alive && setErr("The Office didn’t load. Check your connection and try again."));
    return () => { alive = false; };
  }, [date]);
  function pickWord(w) {
    setWord(word === w ? null : w);
    if (!lex) loadLex().then(setLex).catch(() => {});
    if (!forms) officeGet("forms").then(setForms).catch(() => {});
  }
  function shift(n) { const d = new Date(date + "T12:00:00"); d.setDate(d.getDate() + n); setDate(isoOf(d)); }
  const today = isoOf(new Date());
  const read = prog.oread || [];
  const isRead = read.includes(dayNum(date));
  const streak = officeStreak(read, today);
  async function keepOffline() {
    setSaving("Saving…");
    try {
      const idx = await officeGet("index");
      const yr = +today.slice(0, 4);
      const names = ["index", "common", "forms", ...idx.years.filter(y => y === yr || y === yr + 1).map(y => "days-" + y), ...Array.from({ length: 12 }, (_, i) => String(i + 1).padStart(2, "0"))];
      for (let i = 0; i < names.length; i++) { setSaving(`Saving ${i + 1} of ${names.length}…`); await officeFetch(names[i]); }
      setSaving("Saved: the Office for this year and next works with no signal.");
    } catch (e) { setSaving("Saving stopped: check your connection and try again."); }
  }
  const secs = day && day.sections ? day.sections.map((s, i) => ({ s, i, name: sectionName(s[0]) })) : [];
  const omitted = x => x.s[0].length <= 1 && /\{omittitur\}/.test(x.s[0][0] || "");
  const shown = view === "full" ? secs : secs.filter(x => !omitted(x) && (/^(Hymnus|Lectio|Oratio)/.test(x.name) || x.s[0].some(l => /^\*Lectio \d/.test(l))));
  const chips = shown.map(x => ({ i: x.i, name: x.name || (x.s[0].find(l => /^\*Lectio/.test(l)) || "").replace(/\*/g, "") })).filter(x => x.name);
  const entry = word && forms ? (forms[normForm(word)] || null) : undefined;
  const yrs = day && day.missing ? day.years : null;
  return (
    <div className="flex flex-col gap-4">
      <section className="rounded-lg border border-rule bg-leaf px-5 py-4" aria-label="The day">
        <div className="flex flex-wrap items-center gap-2">
          <Btn onClick={() => shift(-1)} aria-label="Previous day">‹</Btn>
          <label htmlFor="office-date" className="sr-only">Date</label>
          <input id="office-date" type="date" value={date} onChange={e => e.target.value && setDate(e.target.value)} className="rounded-md border border-rule bg-paper px-2 py-1.5 text-[15px] text-ink" />
          <Btn onClick={() => shift(1)} aria-label="Next day">›</Btn>
          {date !== today && <Btn onClick={() => setDate(today)}>Today</Btn>}
        </div>
        {day && !day.missing && (
          <div className="mt-3">
            <h2 lang="la" className="latin text-[1.2rem] font-bold leading-snug text-ink">{day.t}</h2>
            <p className="text-[14px] text-soft">{RANK_EN[day.k] || day.k}{day.o ? ` · ${day.o.replace(/\s+/g, " ")}` : ""}</p>
            <div className="mt-3 flex flex-wrap items-center gap-2">
              <Btn variant={isRead ? "ok" : "primary"} pressed={isRead} onClick={() => onRead(dayNum(date), !isRead)}>{isRead ? "✓ Read" : "Mark as read"}</Btn>
              <span className="text-[13px] text-soft">{streak ? `${streak} day${streak === 1 ? "" : "s"} in a row · ` : ""}{read.length} day{read.length === 1 ? "" : "s"} read in all</span>
            </div>
          </div>
        )}
        {yrs && <p className="mt-3 text-[14px] text-soft">The Office here runs from November {yrs[0]} to December {yrs[yrs.length - 1]}. A rebuild extends it (see the project’s README).</p>}
        {err && <p className="mt-3 text-[14px] text-warn">{err}</p>}
      </section>

      {day && !day.missing && (
        <>
          <div className="flex flex-wrap items-center gap-2 text-[14px] text-soft">
            <div className="flex gap-1 rounded-lg border border-rule bg-paper p-0.5" role="group" aria-label="How much to show">
              {[["lessons", "Hymn, lessons, prayer"], ["full", "Full Matins"]].map(([k, l]) => <button key={k} type="button" aria-pressed={view === k} onClick={() => setView(k)} className={`rounded px-2.5 py-1 ${view === k ? "bg-ink text-paper" : "text-ink"}`}>{l}</button>)}
            </div>
            <label htmlFor="office-en" className="flex items-center gap-1.5"><input id="office-en" type="checkbox" checked={showEn} onChange={e => setShowEn(e.target.checked)} className="h-4 w-4 accent-[#9a2b22]" /> English beside the Latin</label>
          </div>
          {chips.length > 1 && (
            <nav className="flex flex-wrap gap-1.5" aria-label="Sections">
              {chips.map(c => <button key={c.i} type="button" onClick={() => { const el = document.getElementById("office-" + c.i); if (el) el.scrollIntoView({ behavior: "smooth", block: "start" }); }}
                className="rounded border border-rule bg-paper px-2 py-0.5 text-[12px] text-ink hover:border-soft">{c.name.replace(/^Psalmus /, "Ps ").replace(/^Lectio /, "Lectio ")}</button>)}
            </nav>
          )}
          {shown.map(x => <OfficeSection key={date + x.i} sec={x.s} i={x.i} showEn={showEn} onWord={pickWord} sel={word} />)}
          <p className="text-[12px] text-soft">Text and calendar: Divinum Officium (1960 rubrics, as in the 1962 Breviary), with its English translation. Tap any Latin word for its parsing; read the English only when you need it.</p>
          {APP && <div className="flex flex-wrap items-center gap-2"><Btn onClick={keepOffline}>Keep this year’s Office offline</Btn>{saving && <span className="text-[13px] text-ink">{saving}</span>}</div>}
        </>
      )}
      {!day && !err && <p className="text-[15px] text-soft">Loading the Office…</p>}

      {word && (
        <div className="fixed inset-x-0 bottom-0 z-20 max-h-[45vh] overflow-auto border-t border-rule bg-paper px-4 pb-4 shadow-[0_-4px_16px_rgba(0,0,0,0.08)]">
          <div className="mx-auto max-w-[46rem]">
            {lex && forms ? (entry ? <WordPanel lex={lex} word={word} entry={entry} onClose={() => setWord(null)} where={day ? day.t : ""} onTable={onTable} />
              : <div className="mt-4 flex items-baseline justify-between gap-3 text-[15px]"><span><span lang="la" className="latin font-bold">{word}</span> <span className="text-soft">isn’t in the parsed texts. Try the Forms tab or a dictionary.</span></span><button type="button" onClick={() => setWord(null)} className="text-[13px] text-soft underline">Close</button></div>)
              : <p className="mt-4 text-[14px] text-soft">Looking up…</p>}
          </div>
        </div>
      )}
    </div>
  );
}
