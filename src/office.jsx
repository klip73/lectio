function RubricPara({ p, q }) {
  const sub = p.startsWith("  ");
  const t = p.trim();
  const m = t.match(/^(\d+)\.\s+/);
  const body = m ? t.slice(m[0].length) : t;
  const mark = s => {
    if (!q || q.length < 3 || /^\d+$/.test(q)) return s;
    const i = s.toLowerCase().indexOf(q.toLowerCase());
    return i < 0 ? s : <>{s.slice(0, i)}<mark className="bg-rubrictint text-ink">{s.slice(i, i + q.length)}</mark>{s.slice(i + q.length)}</>;
  };
  return (
    <p className={`whitespace-pre-line text-[15px] leading-relaxed text-ink ${sub ? "pl-5" : ""}`}>
      {m && !sub && <strong className="num mr-1 text-rubric">{m[1]}.</strong>}{mark(m && !sub ? body : t)}
    </p>
  );
}
